import type { AppTheme } from "@spatch-kit/theme/theme";

// card/button/focus share the shadow*-prop shape (the boxShadow-only `overlay` is excluded — it is
// consumed directly as a CSS boxShadow, never turned into a var here).
function toShadowVarValue(shadow: AppTheme["shadow"]["card"]) {
  return `${shadow.shadowOffset.width}px ${shadow.shadowOffset.height}px ${shadow.shadowRadius}px rgba(0, 0, 0, ${shadow.shadowOpacity})`;
}

